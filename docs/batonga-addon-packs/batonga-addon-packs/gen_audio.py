for aid, txt in PROMPTS:
    R(aid, txt, "consigne d'exercice",
      "Consigne, pas question. Débit égal. Les accolades sont remplacées à l'enregistrement "
      "par chaque valeur : prévoir une prise par lettre / chiffre.", 2,
      "gabarit — voir la liste des variantes")

by_session = {}
for r in rows: by_session.setdefault(r["session"], []).append(r)

