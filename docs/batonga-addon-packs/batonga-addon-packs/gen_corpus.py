# ── the decodability ledger ──────────────────────────────────────────────
ledger, avail_letters, avail_graphemes, avail_syll = [], [], [], []
for l in sorted([x for x in lessons if x["unitId"] != "chiffres"], key=lambda x: x["order"]):
    if l["focusKind"] == "letter":
        for g in l["glyphs"]:
            if g not in avail_letters: avail_letters.append(g)
    else:
        for g in l["glyphs"]:
            if g not in avail_graphemes: avail_graphemes.append(g)
    for s in syllables:
        if s["lessonId"] == l["id"] and s["text"] not in avail_syll:
            avail_syll.append(s["text"])
    ledger.append(dict(
        lessonId=l["id"], order=l["order"],
        lettersAvailable=list(avail_letters),
        graphemesAvailable=list(avail_graphemes),
        syllablesAvailable=list(avail_syll),
        letterCount=len(avail_letters), syllableCount=len(avail_syll),
        # Everything a distractor generator is allowed to draw from at this point.
        distractorPool=list(avail_letters) + list(avail_graphemes),
    ))
