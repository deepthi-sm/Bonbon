def audio_vowel_key(v):
    return {"é":"e_acute","è":"e_grave","ê":"e_circ"}.get(v, v)

syllables = []
for lid, c, *_rest in CONSONANTS:
    ipa_c = dict((x[0], x[5]) for x in CONSONANTS)[lid]
    vs = TREE_OVERRIDE.get(lid, TREE_VOWELS)
    missing = TREE_MISSING_BRANCH.get(lid, [])
    for v in TREE_VOWELS:
        in_tree = (v in vs) and (v not in missing)
        in_strip = (v in vs) or (lid in TREE_MISSING_BRANCH and v in missing)
        if not (in_tree or in_strip):
            continue
        irr = IRREGULAR.get((c, v))
        v_ipa = {"i":"i","u":"y","o":"o","a":"a","e":"ə","é":"e","è":"ɛ","ê":"ɛ"}[v]
        syllables.append(dict(
            id=f"{c}{v}", text=f"{c}{v}", consonant=c, vowel=v,
            ipa=(irr[0] if irr else ipa_c) + v_ipa,
            lessonId=lid, order=int(lid[1:]),
            inPrintedTree=in_tree, inPrintedStrip=in_strip,
            derived=DERIVED.get(lid, {}).get(v, []),
            audioId=f"syll.{c}{audio_vowel_key(v)}",
            irregular=bool(irr), note=(irr[1] if irr else None),
            verifyAgainstSource=bool(irr),
        ))
