def phoneme_class(ipa):
    if ipa in CLUSTERS: return "groupe-consonantique"
    if ipa == "∅": return "muette"
    if any(c in ipa for c in "̃"): return "voyelle-nasale"
    if ipa in {"j","ɥij","aj","ɛj","œj","ij","uj","wa","je","ɥ"}: return "semi-voyelle"
    if ipa[0] in "iyoɔaəeɛuøœ": return "voyelle-orale"
    return "consonne"

